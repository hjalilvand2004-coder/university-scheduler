def update_instructors(db_path='university_scheduler.db'):
    """به‌روزرسانی فیلد max_teaching_units در جدول instructors"""
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()

    # ۱. بررسی وجود جدول
    cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='instructors'")
    if not cursor.fetchone():
        print("❌ جدول instructors در دیتابیس وجود ندارد!")
        conn.close()
        return

    # ۲. بررسی وجود ستون max_teaching_units و افزودن در صورت نیاز
    cursor.execute("PRAGMA table_info(instructors)")
    columns = [col[1] for col in cursor.fetchall()]
    if 'max_teaching_units' not in columns:
        try:
            cursor.execute("ALTER TABLE instructors ADD COLUMN max_teaching_units INTEGER;")
            print("✅ ستون 'max_teaching_units' با موفقیت اضافه شد.")
        except sqlite3.OperationalError as e:
            print("⚠️ خطا در افزودن ستون:", e)
            conn.close()
            return
    else:
        print("ℹ️ ستون 'max_teaching_units' از قبل وجود دارد.")

    # ۳. به‌روزرسانی رکوردها بر اساس کد استاد
    updated = 0
    not_found = []
    for code, units in data.items():
        cursor.execute(
            "UPDATE instructors SET max_teaching_units = ? WHERE code = ?",
            (units, str(code))
        )
        if cursor.rowcount > 0:
            updated += 1
        else:
            not_found.append(code)

    conn.commit()
    conn.close()

    print(f"✅ تعداد رکوردهای به‌روز شده: {updated}")
    if not_found:
        print(f"⚠️ کدهای زیر در جدول یافت نشدند (تعداد {len(not_found)}): {not_found}")

